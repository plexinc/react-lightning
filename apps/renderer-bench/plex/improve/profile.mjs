// node profile.mjs <own|stock> <outPrefix>: CPU profiles (100 us) at 4x for load, steps (8 down/8 up @700) and held Down (@80).
import { writeFileSync } from 'node:fs';
import { open, reachHome, waitIdle, steps, hold, rendererStats } from './common.mjs';
const [variant, prefix] = process.argv.slice(2);
const c = await open(variant);
await c.send('Profiler.enable');
await c.send('Profiler.setSamplingInterval', { interval: 100 });
await c.send('Emulation.setCPUThrottlingRate', { rate: 4 });
await c.send('Profiler.start');
await reachHome(c, 6000);
let { profile } = await c.send('Profiler.stop');
writeFileSync(`${prefix}-load.cpuprofile`, JSON.stringify(profile));
const s0 = await c.evaluate(rendererStats);
await c.evaluate(`__probe.frames = []; __probe.gl.draw = 0; __probe.gl.tex = 0; __probe.gl.sub = 0; true`);
await c.send('Profiler.start');
await steps(c, [...Array(8).fill('ArrowDown'), ...Array(8).fill('ArrowUp')], 700);
await waitIdle(c);
({ profile } = await c.send('Profiler.stop'));
writeFileSync(`${prefix}-steps.cpuprofile`, JSON.stringify(profile));
const s1 = await c.evaluate(rendererStats);
const gl1 = await c.evaluate('__probe.gl');
await c.send('Profiler.start');
await hold(c, 'ArrowDown', 25, 80);
await waitIdle(c);
await steps(c, Array(12).fill('ArrowUp'), 300);
await waitIdle(c);
({ profile } = await c.send('Profiler.stop'));
writeFileSync(`${prefix}-held.cpuprofile`, JSON.stringify(profile));
const s2 = await c.evaluate(rendererStats);
await c.send('Emulation.setCPUThrottlingRate', { rate: 1 });
console.log(JSON.stringify({ variant, afterLoad: s0, afterSteps: s1, glSteps: gl1, afterHeld: s2 }));
c.close();
